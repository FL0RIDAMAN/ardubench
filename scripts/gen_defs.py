# Generates src/mavlink/defs.js from pymavlink's ardupilotmega dialect,
# so message layouts and CRC_EXTRA values come from the official definitions.
from pymavlink.dialects.v20 import ardupilotmega as m
import json, re

NAMES = ["HEARTBEAT","SYS_STATUS","PARAM_REQUEST_READ","PARAM_REQUEST_LIST","PARAM_VALUE",
         "PARAM_SET","COMMAND_LONG","COMMAND_ACK","STATUSTEXT","ESC_TELEMETRY_1_TO_4",
         "AUTOPILOT_VERSION","GPS_RAW_INT","LOG_REQUEST_LIST","LOG_ENTRY"]
out = {}
for n in NAMES:
    cls = getattr(m, "MAVLink_" + n.lower() + "_message")
    fields = []
    for fname in cls.ordered_fieldnames:
        i = cls.fieldnames.index(fname)
        t = cls.fieldtypes[i]
        alen = cls.array_lengths[cls.ordered_fieldnames.index(fname)]
        fields.append([fname, t, alen])
    ext = len(cls.fieldnames) and getattr(cls, "extensions_start", None)
    out[n] = {"id": cls.id, "crcExtra": cls.crc_extra, "fields": fields}
print("// AUTO-GENERATED by scripts/gen_defs.py from pymavlink (ardupilotmega dialect). Do not edit by hand.")
print("// Each field: [name, type, arrayLength]. Fields are in wire order (largest types first).")
print("export const MESSAGES = " + json.dumps(out, separators=(",", ":")).replace("},\"", "},\n  \"") + ";")
